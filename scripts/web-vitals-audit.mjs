#!/usr/bin/env node
// Lighthouse-alapú Web Vitals audit script.
// Használat: BASE_URL=https://www.jovod.hu node scripts/web-vitals-audit.mjs
// Vagy lokálisan: node scripts/web-vitals-audit.mjs

import { writeFile, mkdir } from "node:fs/promises";
import { spawn } from "node:child_process";
import { existsSync } from "node:fs";

const BASE_URL = process.env.BASE_URL ?? "https://www.jovod.hu";
const OUT_DIR = process.env.OUT_DIR ?? ".lighthouse";

const ROUTES = [
  "/",
  "/mai-lap",
  "/harom-lap",
  "/horoszkop",
  "/szammisztika",
  "/numerologia",
  "/magazin",
  "/tarot",
  "/kinai-horoszkop",
  "/jiking",
  "/arak",
];

function run(cmd, args, opts = {}) {
  return new Promise((resolve, reject) => {
    const p = spawn(cmd, args, { stdio: "inherit", ...opts });
    p.on("close", (code) => (code === 0 ? resolve() : reject(new Error(`${cmd} exit ${code}`))));
    p.on("error", reject);
  });
}

async function main() {
  if (!existsSync(OUT_DIR)) await mkdir(OUT_DIR, { recursive: true });

  const summary = [];
  for (const route of ROUTES) {
    const url = `${BASE_URL}${route}`;
    const safe = route === "/" ? "home" : route.replace(/^\//, "").replace(/[/]/g, "_");
    const jsonPath = `${OUT_DIR}/${safe}.json`;
    console.log(`\n→ Auditing ${url}`);
    try {
      await run("npx", [
        "--yes",
        "lighthouse",
        url,
        "--quiet",
        "--chrome-flags=--headless=new --no-sandbox",
        "--only-categories=performance,seo,accessibility,best-practices",
        "--output=json",
        `--output-path=${jsonPath}`,
        "--preset=desktop",
      ]);
      const report = JSON.parse(await (await import("node:fs/promises")).readFile(jsonPath, "utf8"));
      const c = report.categories;
      const a = report.audits;
      summary.push({
        url,
        perf: Math.round((c.performance?.score ?? 0) * 100),
        seo: Math.round((c.seo?.score ?? 0) * 100),
        a11y: Math.round((c.accessibility?.score ?? 0) * 100),
        bestPractices: Math.round((c["best-practices"]?.score ?? 0) * 100),
        lcp: a["largest-contentful-paint"]?.displayValue ?? "—",
        cls: a["cumulative-layout-shift"]?.displayValue ?? "—",
        inp: a["interaction-to-next-paint"]?.displayValue ?? "—",
        fcp: a["first-contentful-paint"]?.displayValue ?? "—",
        tbt: a["total-blocking-time"]?.displayValue ?? "—",
      });
    } catch (e) {
      console.error(`  ✗ Audit failed: ${e.message}`);
      summary.push({ url, error: e.message });
    }
  }

  await writeFile(`${OUT_DIR}/summary.json`, JSON.stringify(summary, null, 2));
  const md = [
    `# Web Vitals audit — ${new Date().toISOString()}`,
    ``,
    `Base URL: ${BASE_URL}`,
    ``,
    `| Route | Perf | SEO | A11y | BP | LCP | CLS | INP | FCP | TBT |`,
    `|---|---:|---:|---:|---:|---|---|---|---|---|`,
    ...summary.map((s) =>
      s.error
        ? `| ${s.url} | ERROR | | | | ${s.error} | | | | |`
        : `| ${s.url} | ${s.perf} | ${s.seo} | ${s.a11y} | ${s.bestPractices} | ${s.lcp} | ${s.cls} | ${s.inp} | ${s.fcp} | ${s.tbt} |`,
    ),
    ``,
    `_Generated by scripts/web-vitals-audit.mjs_`,
  ].join("\n");
  await writeFile(`${OUT_DIR}/summary.md`, md);
  console.log(`\n✓ Done. Summary: ${OUT_DIR}/summary.md`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});